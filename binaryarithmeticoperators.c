/*Program to use binary arithmetic operators*/
#include <stdio.h>
int main()
{
    int a=10,b=6,result;
    //Addition
    result=a+b;
    printf("a+bis%d\n",result);
    //Subtraction
    result=a-b;
    printf("a-bis%d\n",result);
    //Multiplication
    result=a*b;
    printf("a*bis%d\n",result);
    //Division
    result=a/b;
    printf("a/bis%d\n",result);
    //Modulus
    result=a%b; 
    printf("a%bis%d\n",result);
    return 0;
}    

